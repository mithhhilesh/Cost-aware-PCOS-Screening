"""Run: python -m streamlit run streamlit_app.py"""
from pathlib import Path
import json
import threading
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import joblib
import shap
import streamlit as st
from pcos_support import (prepare_patient, probability_function, explain_probability,
                          contribution_table, patient_explanation)

ROOT = Path(__file__).resolve().parent
ARTIFACTS = ROOT / 'artifacts'
st.set_page_config(page_title='PCOS screening ', page_icon='🌿', layout='wide')
st.title('PCOS screening dashboard')
st.caption('Feature-group selection · model comparison · individual SHAP explanations')
st.info('Screening support. The score is not a diagnosis or a validated individual risk. '
        'Review the result with a clinician; a negative prediction does not rule out PCOS.')
if not (ARTIFACTS / 'manifest.json').exists():
    st.warning('First run the notebook through “Export the selected models and dashboard”. '
               'Place its artifacts folder beside this app, then restart the dashboard.')
    st.stop()

manifest = json.loads((ARTIFACTS / 'manifest.json').read_text(encoding='utf-8'))
st.sidebar.header('Available information')
labels = {'A0_full': 'All features: symptoms, labs and ultrasound',
          'A1_no_very_high': 'Symptoms and blood tests (no ultrasound)',
          'A2_no_very_high_high': 'Symptoms and vitamin D',
          'A4_low_only': 'Low-cost symptoms and measurements'}
stages = [s for s in manifest['groups'] if s != 'A3_low_medium']
stage = st.sidebar.selectbox('Feature group', stages, format_func=lambda s: labels.get(s, s))
st.sidebar.caption('A3 is omitted here because it duplicates A2. Every group uses its own fitted subset model.')
selected = manifest['groups'][stage]
st.sidebar.write('Selected model: **' + selected['model'] + '**')
st.sidebar.caption(manifest['selection_rule'])

@st.cache_resource
def load_bundle(stage_name, modified):
    # Only load files generated by this notebook; never accept uploaded pickle/joblib objects.
    return joblib.load(ARTIFACTS / (stage_name + '.joblib')), threading.RLock()

bundle_path = ARTIFACTS / (stage + '.joblib')
bundle, model_lock = load_bundle(stage, bundle_path.stat().st_mtime_ns)
predict_tab, compare_tab, methods_tab = st.tabs(['Patient prediction', 'Compare models', 'Methods'])
with compare_tab:
    comparisons = pd.read_csv(ARTIFACTS / 'model_comparison.csv')
    analysis = st.radio('Analysis', ['Primary', 'Sensitivity'], horizontal=True)
    compare_stage = stage
    available_stages = list(comparisons.loc[comparisons.analysis == analysis, 'feature_set'].unique())
    if stage not in available_stages:
        st.caption('The starter bundle contains saved seven-model probability evaluations for the '
                   'full and low-cost groups. Run notebook Section 10 for the complete repeated-CV comparison.')
        compare_stage = st.selectbox('Comparison feature group', available_stages,
                                     format_func=lambda s: labels.get(s, s))
    rows = comparisons[(comparisons.analysis == analysis) & (comparisons.feature_set == compare_stage)]
    rows = rows.sort_values('accuracy_mean', ascending=False)
    metric = st.selectbox('Metric', ['accuracy', 'recall', 'f1', 'roc_auc', 'specificity', 'balanced_accuracy'])
    fig, ax = plt.subplots(figsize=(10, 5))
    colors = ['#db7c36' if 'RF + LR' in n else '#287d8e' for n in rows.model]
    spread = rows[metric + '_std'] if metric + '_std' in rows else pd.Series(np.nan, index=rows.index)
    has_spread = spread.notna().all()
    ax.barh(rows.model, 100*rows[metric + '_mean'], xerr=100*spread if has_spread else None,
            color=colors, capsize=3)
    ax.invert_yaxis()
    ax.set(xlim=(0, 100), xlabel=metric.replace('_', ' ').title() + ' (%)',
           title='Seven models; orange = hybrids' + ('; mean ± fold SD' if has_spread else '; held-out OOF scores'))
    fig.tight_layout()
    st.pyplot(fig)
    plt.close(fig)
    st.dataframe(rows, hide_index=True)
    st.caption(manifest.get('evaluation_label', 'Repeated stratified CV: 5 folds × 10 repeats; mean ± fold SD'))
    st.caption('SD, when shown, describes fold spread, not a confidence interval. '
               'Selection uses primary recall, then F1, ROC-AUC and accuracy.')
with methods_tab:
    st.write('Each group uses the highest-ranked candidate among five standalone models and '
             'RF + LR stacking / soft voting, followed by a full-data refit for inference. '
             'The comparison scores come from cross-validation, not that refit.')
    st.write('SHAP explains the entire fitted pipeline in PCOS-class probability units. '
             'Positive values raise the score and negative values lower it relative to the '
             'reference background. Correlated features can share credit; this is not a causal explanation.')
    st.write('The primary analysis includes features that may overlap diagnostic criteria. '
             'The sensitivity analysis removes these features. Reusing CV for selection gives '
             'exploratory performance estimates; external validation is still required.')
    st.caption('Inputs are processed in memory. This app does not save patient forms or prediction history.')
    st.json(manifest['versions'])
with predict_tab:
    st.subheader(labels.get(stage, stage))
    st.write(f"Model: **{bundle['model_name']}** · {len(bundle['features'])} required inputs")
    st.caption('Use the units shown. No patient values are filled automatically. Cycle length uses '
               'the original dataset definition; confirm this field before clinical use.')
    entered = {}
    with st.form('patient_' + stage):
        for tier in dict.fromkeys(bundle['schema'][f]['tier'] for f in bundle['features']):
            st.markdown('**' + tier + '**')
            cols = st.columns(3)
            for i, f in enumerate(f for f in bundle['features'] if bundle['schema'][f]['tier'] == tier):
                spec = bundle['schema'][f]
                help_text = (f"Dataset observed range: {spec['min_observed']:g}–{spec['max_observed']:g}. "
                             'This range is not a clinical normal range.')
                with cols[i % 3]:
                    if spec['choices'] is not None:
                        options = spec['choices']
                        def option_label(v, feature=f):
                            if feature == 'Cycle(R/I)':
                                return {2.: 'Regular (code 2)', 4.: 'Irregular (code 4)'}.get(v, str(v))
                            return {0.: 'No', 1.: 'Yes'}.get(v, str(v))
                        entered[f] = st.selectbox(spec['label'], options, index=None,
                                                  format_func=option_label, key=stage+f, help=help_text)
                    else:
                        entered[f] = st.number_input(spec['label'], min_value=0.0, value=None,
                                                     step=0.1, key=stage+f, help=help_text)
        submitted = st.form_submit_button('Predict and explain')
    if submitted:
        missing = [f.strip() for f, v in entered.items() if v is None]
        if missing:
            st.error('Complete all inputs: ' + ', '.join(missing))
        else:
            raw = pd.DataFrame([entered], columns=bundle['features'], dtype=float)
            clean = prepare_patient(raw)
            corrected = [f.strip() for f in clean if clean[f].isna().any()]
            if corrected:
                st.error('These values would be treated as missing by the notebook. '
                         'Please check or correct them before prediction: ' + ', '.join(corrected))
            elif not np.isfinite(clean.to_numpy()).all():
                st.error('All values must be finite.')
            else:
                unusual = [f.strip() for f in clean if
                           not bundle['schema'][f]['min_observed'] <= clean[f].iloc[0] <= bundle['schema'][f]['max_observed']]
                if unusual:
                    st.warning('Outside the training data range; the model may be unreliable for: ' + ', '.join(unusual))
                with st.spinner('Computing prediction and feature contributions...'):
                    # Cached models and matplotlib are shared resources; serialize their use.
                    with model_lock:
                        score = float(probability_function(bundle['model'], bundle['features'])(clean)[0])
                        explanations = explain_probability(bundle['model'], bundle['background'], clean)
                        explanation = explanations[0]
                        st.metric('PCOS-class model score', f'{score:.1%}')
                        st.write(patient_explanation(explanation, clean.iloc[0], score))
                        shap.plots.waterfall(explanation, max_display=12, show=False)
                        fig = plt.gcf()
                        fig.tight_layout()
                        st.pyplot(fig)
                        plt.close(fig)
                        st.caption('Waterfall values are probability units: +0.05 means +5 percentage points. '
                                   'The reference score plus all contributions equals the displayed model score.')
                        table = contribution_table(explanation, clean.iloc[0])
                        st.dataframe(table, hide_index=True)
